// Задача 000267 (потребители NO-OP-статов; находка C1 ретро-анализа
// RETRO-20261024; ТЗ tasks/pending/000267.md; контракт
// memory/000267-noop-stat-consumers.md §2.6) — RED-тест (docs only;
// код игры и существующие тесты НЕ меняются на красной стадии).
//
// ТЗ: в spec/spells.md «## Действия заклинаний» появляется буллет
// «Потребление статов» — кто читает какой стат (реген/вампиризм/
// drain/попадание_вниз (оба пути)/lifesteal) + исключение зоны-реген
// («единственная зона-стат, тикающая каждый раунд») + строка
// «потребителей нет» для отражения/иммунитет_контроля/ход(ы).
//
// Красные «отсутствием» (осмысленно — правки SPEC ещё нет, не
// синтаксис: spec/spells.md существует и читается, H2 «## Действия
// заклинаний» на месте — падение ERR_ASSERTION по отсутствию нового
// текста). Прецеденты: 000266 (wording-пины + нормализация; 1 правка
// = 1 test), 000218 (wording-пины + нормализация). Нормализация
// белых ОБЯЗАТЕЛЬНА (SPEC переносит строки ~64-70 кол., фразы
// ломаются по словам) + регистронезависимость (пины — срединные
// фразы буллета, но начало строк в SPEC может капситься). Хелперы
// esc/h2/norm — 1:1 из tests/spec-000266-wording.test.js.
//
// expectedRedCount (файл) = 1. Файл НЕ создаёт файлов в spec/
// (R1 spec-split: ровно 23).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — пины читают подфайлы напрямую.
const SPELLS = fs.readFileSync(path.join(ROOT, 'spec', 'spells.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» внутри текста раздела.
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация: белые → пробел, регистр → lower (фразы, сломавшиеся
// переносом, встают в строку; капс начала строки не ломает пин).
function norm(s) {
  return s.replace(/\s+/g, ' ').toLowerCase();
}

// Срез: H2 «## Действия заклинаний» → следующий H2 («Каст вне боя»).
const D = () => norm(h2(SPELLS, 'Действия заклинаний'));

test('SPEC 000267: spells.md «Действия заклинаний» — буллет «Потребление статов» (кто читает какой стат; зона-реген — единственная тикающая; потребители нет — для отражения/иммунитет_контроля/хода)', () => {
  const d = D();
  assert.ok(
    d.includes('потребление статов'),
    '«## Действия заклинаний»: буллет «Потребление статов» (000267) '
    + 'отсутствует — ТЗ требует зафиксировать, кто читает какой стат');
  assert.ok(
    d.includes('ровно turns тиков, включая каст'),
    '«Потребление статов»: строка «реген» — тик startRound, «ровно '
    + 'turns тиков, включая каст» (контракт §2.6) отсутствует');
  assert.ok(
    d.includes('единственная зона-стат, тикающая каждый раунд'),
    '«Потребление статов»: исключение «зона {реген} — единственная '
    + 'зона-стат, тикающая каждый раунд (прочие зоны — однократные)» '
    + 'отсутствует (факт Z2)');
  assert.ok(
    d.includes('вампиризм — удар игрока при попадании'),
    '«Потребление статов»: строка «вампиризм — удар игрока при '
    + 'попадании: кастер +round(v×факт)» отсутствует');
  assert.ok(
    d.includes('параметры.value'),
    '«Потребление статов»: строка drain «урон» + параметры.value '
    + '(000069/000072): кастер +round(value×факт) отсутствует');
  assert.ok(
    d.includes('удар призывного лечит его на полный нанесённый урон'),
    '«Потребление статов»: строка lifesteal (призыв, mt.traits; '
    + '000087 shadow_wraith) «удар призывного лечит его на полный '
    + 'нанесённый урон» отсутствует');
  assert.ok(
    d.includes('потребителей нет'),
    '«Потребление статов»: строка «отражение, иммунитет_контроля, '
    + 'ход, ход_вниз — потребителей нет» отсутствует (RETRO-20261024 '
    + '§9.6: спеллы с этими статами не вводить до появления '
    + 'потребителей)');
  assert.equal(
    d.split('потребление статов').length - 1, 1,
    'буллет «Потребление статов» — ровно ОДИН (нет дублей)');
});
