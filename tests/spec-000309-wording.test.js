// 20%→90% с навыком крафта, разборка качает навык сборки; ТЗ
// tasks/pending/000309.md; контракт memory/000309-disassemble.md) —
// RED-тест (SPEC-слово). Код игры, существующие тесты и spec/ НЕ
// меняются на красной стадии: правка spec/craft.md (H2 «Разборка
// предметов» в конец файла, draft = memory-файл строки 277–303,
// 27 строк) + ре-пин SPEC_FILE_LINES (tests/spec-split.test.js,
// craft.md 149 → 176, 67 → 68 H2) — зелёная стадия, ТОМ ЖЕ
// коммите (протоколы 000159 §5.1 / 000218 D11; контракт §8).
//
// W: spec/craft.md — НОВЫЙ H2 «## Разборка предметов» (хвост файла,
// 27 строк; craft.md 149 → 176):
//   * канонический рецепт — базовый, «минимальным `уровнем`», при
//     равенстве — «первый по порядку каталога»; покрытие
//     «(298 из 511)»;
//   * формула «20% + 70% × (L − 1) / 99» (канон ×/−), L — уровень
//     вида: «L=1 — 20%», «L=100 — 90%»;
//   * опыт «10 + «уровень»» (практика, «потолок практикой»);
//   * «не требует изученности» (гейт «вид не изучен» — только
//     изготовление);
//   * «Не «разборка постройки»» — расшифровка термина (без числа
//     30%: разборка постройки = возврат ЗОЛОТА, spec/buildings.md);
//   * UI: «кнопка «разобрать»» во вкладке «Инвентарь»;
//   * НЕГАТИВ: «30%» в срезе НЕТ (термин не перепутан);
//   * guard specLines(craft.md) = 176 (149 + 27 строк draft; ТОТ
//     ЖЕ N, что SPEC_FILE_LINES craft.md — ре-пин в том же
//     коммите, 000159 §5.1).
//
// Срез: h2() по имени (раздела на HEAD нет — падение в h2).
// readFileSync файла ОДИН РАЗ; norm() — коллапс белых (SPEC
// переносит строки, паттерн 000235.04.01 / 000296-wording).
//
// Краснота ОСМЫСЛЕННАЯ (файл существует и читается — 149 строк,
// раздела нет): падение в h2() (подраздел не найден) + guard
// specLines = 149 ≠ 176.
//
// expectedRedCount (файл) = 1 (W). Красная стадия: npm test — ровно
// 18 новых «not ok» (D1–D13, UI-1..UI-4, W), остальное зелёное
// (включая spec-split — spec/ на красной стадии не трогается).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const CRAFTMD = fs.readFileSync(path.join(ROOT, 'spec', 'craft.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» (до следующего '\n## ' или конца).
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл существует — осмысленная краснота).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

// Конвенция 000159 R5: split('\n') + pop хвостового ''.
function specLines(s) {
  const lines = s.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  return lines.length;
}

test('SPEC 000309 W: spec/craft.md — «Разборка предметов» (хвост файла): формула 20% + 70% × (L − 1) / 99 (L=1 — 20%, L=100 — 90%), канонический рецепт (минимальным `уровнем`, первый по порядку каталога, 298 из 511), опыт 10 + «уровень» (потолок практикой), не требует изученности, «Не «разборка постройки»», кнопка «разобрать» в «Инвентарь», NEG «30%», guard 176', () => {
  const sc = h2(CRAFTMD, 'Разборка предметов');
  phrase(sc, '«Разборка предметов»', '20% + 70% × (L − 1) / 99',
    'формула шанса возврата (канон ×/−) не зафиксирована');
  phrase(sc, '«Разборка предметов»', 'L=1 — 20%',
    'граница L=1 — 20% не зафиксирована');
  phrase(sc, '«Разборка предметов»', 'L=100 — 90%',
    'граница L=100 — 90% не зафиксирована');
  phrase(sc, '«Разборка предметов»', 'минимальным `уровнем`',
    'правило канонического рецепта (минимальный `уровень`) '
    + 'не зафиксировано');
  phrase(sc, '«Разборка предметов»', 'первый по порядку каталога',
    'тай-брейк (первый по порядку каталога) не зафиксирован');
  phrase(sc, '«Разборка предметов»', '(298 из 511)',
    'покрытие: предметы, поддающиеся разборке (298 из 511), '
    + 'не зафиксировано');
  phrase(sc, '«Разборка предметов»', '10 + «уровень»',
    'формула опыта (10 + «уровень» рецепта) не зафиксирована');
  phrase(sc, '«Разборка предметов»', 'потолок практикой',
    'потолок практикой (ограничение опыта) не зафиксирован');
  phrase(sc, '«Разборка предметов»', 'не требует изученности',
    'отсутствие гейта «вид не изучен» не зафиксировано');
  phrase(sc, '«Разборка предметов»', 'Не «разборка постройки»',
    'расшифровка термина (разборка ≠ разборка постройки, '
    + 'spec/buildings.md) не зафиксирована');
  phrase(sc, '«Разборка предметов»', 'кнопка «разобрать»',
    'UI (кнопка «разобрать») не зафиксирован');
  phrase(sc, '«Разборка предметов»', 'Инвентарь',
    'UI (вкладка «Инвентарь») не зафиксирован');
  assert.ok(!norm(sc).includes('30%'),
    '«Разборка предметов»: «30%» в разделе — путаница с разборкой '
    + 'постройки (spec/buildings.md, возврат золота)');
  assert.equal(specLines(CRAFTMD), 176,
    'spec/craft.md: строк != 176 — H2 «Разборка предметов» (27 '
    + 'строк draft, craft.md 149→176) + ре-пин SPEC_FILE_LINES '
    + '(000159 §5.1) в том же коммите');
});
