// --- T9: forbid-цепь — зуб длины/уникальности/включения (000372) -------------

test('000320.35 T9: forbid-цепь 000372 (.34→.35) — guard-массив T5 этого файла РОВНО 127 и без дублей, предыдущего звена .34 РОВНО 123 и без дублей, prev ⊆ own, дельта — РОВНО 4 оборота Ухвата (формула наследования; хвост цепи — резерв 4 кречета НЕ в списке, он для .36)', () => {
  const extract = (file, marker) => {
    const src = fs.readFileSync(file, 'utf8');
    const anchor = "test('" + marker;
    const at = src.indexOf(anchor);
    assert.ok(at >= 0,
      path.basename(file) + ': якорь T5 «' + marker + '» не найден — '
      + 'порча имени теста-носителя цепи ловится здесь (ERR_ASSERTION, '
      + 'не крах загрузки)');
    const m = src.slice(at).match(/for \(const w of \[([\s\S]*?)\]\)/);
    assert.ok(m,
      path.basename(file) + ': guard-массив не найден после якоря T5');
    return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
  };
  const EXPECT_ADDS = [
    'утварь любят не за блеск, а за хват', 'нагретый лист слушается ровных рук',
    'сталь служит тому, кто её не торопит', 'крепка утварь, когда рука легка'];
  const own = extract(__filename, '000320.35 T5:');
  const prevFile = path.join(__dirname, 'npc-000320.34.test.js');
  assert.ok(fs.existsSync(prevFile),
    'предыдущее звено цепи tests/npc-000320.34.test.js существует');
  const prev = extract(prevFile, 'T5:');
  const p34 = fs.readFileSync(prevFile, 'utf8');
  const discMine34 = [...p34.match(/const MINE = \[([\s\S]*?)\];/)[1]
    .matchAll(/'([^']*)'/g)].map((x) => x[1]);
  assert.deepEqual(EXPECT_ADDS, discMine34,
    'копии EXPECT_ADDS ≡ дисковой MINE-константе файла .34 '
    + '(правило 000390: формы ТОЛЬКО с диска — расхождение транскрипции '
    + 'ловится здесь); факт диска: ' + JSON.stringify(discMine34));
  assert.equal(own.length, 127,
    'guard-массив T5 этого файла — РОВНО 127 (пин по диску; вырез или '
    + 'лишний элемент ловятся здесь); факт: ' + own.length);
  assert.equal(new Set(own).size, own.length,
    'guard-массив этого файла — элементы уникальны (дубль ловится здесь)');
  assert.equal(prev.length, 123,
    'guard-массив T5 .34 — РОВНО 123 (то же число пинует T9 файла .34 — '
    + 'двойное покрытие); факт: ' + prev.length);
  assert.equal(new Set(prev).size, prev.length,
    'guard-массив .34 — элементы уникальны');
  const ownSet = new Set(own);
  const lost = [...new Set(prev)].filter((x) => !ownSet.has(x));
  assert.deepEqual(lost, [],
    'строгое включение prev ⊆ own — ни один элемент .34 не потерян; '
    + 'потеряно: ' + JSON.stringify(lost));
  const prevSet = new Set(prev);
  const adds = own.filter((x) => !prevSet.has(x));
  assert.deepEqual([...adds].sort(), [...EXPECT_ADDS].sort(),
    'дельта (own минус prev) — РОВНО 4 оборота Ухвата = MINE-константа '
    + 'файла .34 (формула наследования '
    + 'memory/000320-tool_smith.md); СВОИ 4 оборота кречета (резерв '
    + '.36 по memory/000320-archery_instructor.md) в списке НЕ сидят; '
    + 'факт: ' + JSON.stringify(adds));
});
