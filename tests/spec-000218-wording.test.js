const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — пины читают подфайлы напрямую.
// 000218: каждый из 3 затронутых файлов — ОТДЕЛЬНО (срез в пределах файла).
const COMPANIONS = fs.readFileSync(path.join(ROOT, 'spec', 'companions.md'), 'utf8');
const DUNGEONS_STORAGE = fs.readFileSync(path.join(ROOT, 'spec', 'dungeons-storage.md'), 'utf8');
const ITEMS = fs.readFileSync(path.join(ROOT, 'spec', 'items.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H1-раздела: строка '# <name>' → до следующего '\n# '.
function h1(text, name) {
  const m = text.match(new RegExp('^' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: раздел «' + name + '» не найден');
  const i = m.index;
  const j = text.indexOf('\n# ', i + 1);
  return text.slice(i, j === -1 ? text.length : j);
}

// Срез H2-подраздела «## <name>» внутри текста раздела.
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// W1-срез: «Спутники → Бой» (H1 '# Спутники' → H2 'Бой').
const W1 = () => norm(h2(h1(COMPANIONS, '# Спутники'), 'Бой'));
// W2-срез: H2 «## Залежи» → EOF (единственный H2 dungeons-storage.md).
const W2 = () => norm(h2(DUNGEONS_STORAGE, 'Залежи'));
// W3-срез: H2 «## Природные ингредиенты» → EOF (последний H2 items.md).
const W3 = () => norm(h2(ITEMS, 'Природные ингредиенты'));

