const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const MOBSMD = fs.readFileSync(path.join(ROOT, 'spec', 'mobs.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» (до следующего '\n## ' или конца).
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл существует — осмысленная краснота).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

// Конвенция 000159 R5: split('\n') + pop хвостового ''.
function specLines(s) {
  const lines = s.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  return lines.length;
}

test('SPEC 000303 W: spec/mobs.md — буллет «Агрессивность»: D = уровень группы − уровень Флогистона (000303), D ≤ 0 — без изменений, aggroDistance(D) = min(4, ceil(D/2)), aggroChance(D) = min(0.6, 0.1·D), ролл в потоке wanderStep, мобы глобальной карты — не затронуты, guard 139', () => {
  const sc = h2(MOBSMD, 'Агрессивность');
  phrase(sc, '«Агрессивность»', 'D = уровень группы − уровень Флогистона (000303)',
    'формула разности уровней (маркер 000303) не зафиксирована');
  phrase(sc, '«Агрессивность»', 'D ≤ 0 — без изменений',
    'бит-в-бит граница D ≤ 0 (legacy-блуждание) не зафиксирована');
  phrase(sc, '«Агрессивность»', 'aggroDistance(D) = min(4, ceil(D/2))',
    'формула дистанции агрессии (кап 4) не зафиксирована');
  phrase(sc, '«Агрессивность»', 'aggroChance(D) = min(0.6, 0.1·D)',
    'формула шанса (0.1 за уровень разности, кап 0.6) не зафиксирована');
  phrase(sc, '«Агрессивность»', 'Мобы глобальной карты — не затронуты',
    'граница 0-diff (мобы глобальной карты) не зафиксирована');
  assert.equal(specLines(MOBSMD), 146,
    'spec/mobs.md: строк != 146 — буллет «Агрессивность» (13 строк '
    + 'draft, mobs.md 126→139) + 000365: +7 (docs-эррата b19 П.3 — '
    + 'оговорка видимости агро-окружности в хвост буллета «Состав '
    + 'групп», 139→146) + ре-пин SPEC_FILE_LINES и G2 (000159 §5.1) '
    + 'в том же коммите');
});
