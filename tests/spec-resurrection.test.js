test('SPEC 000156: «Контракт и жалованье» — гибель больше не «окончательна» (D1)', () => {
  const k = h2(h1('# Спутники'), 'Контракт и жалованье');
  assert.ok(!/окончательна/.test(k),
    '«Контракт и жалованье»: строка «гибель — окончательна» заменена не ' +
    'была (design §6.1: гибель записывается с сохранением уровня/опыта/лояльности)');
  assert.match(k, /список погибших/,
    '«Контракт и жалованье»: гибель записывается в список погибших');
  assert.match(k, /возврат\s*—\s*воскрешением/,
    '«Контракт и жалованье»: возврат — воскрешением (ссылка на раздел)');
});

