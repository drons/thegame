// --- T9: forbid-цепь — зуб длины/уникальности/включения (000372) -------------

test('000320.37 T9: forbid-цепь 000372 (.36→.37) — guard-массив T5 этого файла РОВНО 135 и без дублей, предыдущего звена .36 РОВНО 131 и без дублей, prev ⊆ own, дельта — РОВНО 4 оборота Намёта (формула наследования; хвост цепи — резерв 4 канителя НЕ в списке, он для .38)', () => {
  const extract = (file, marker) => {
    const src = fs.readFileSync(file, 'utf8');
    const anchor = "test('" + marker;
    const at = src.indexOf(anchor);
    assert.ok(at >= 0,
      path.basename(file) + ': якорь T5 «' + marker + '» не найден — '
      + 'порча имени теста-носителя цепи ловится здесь (ERR_ASSERTION, '
      + 'не крах загрузки)');
    const m = src.slice(at).match(/for \(const w of \[([\s\S]*?)\]\)/);
    assert.ok(m,
      path.basename(file) + ': guard-массив не найден после якоря T5');
    return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
  };
  const EXPECT_ADDS = [
    'меткость растёт не из силы, а из терпенья',
    'целиться — значит выбирать, а не желать',
    'промах живёт в спешке, а не в ветре',
    'десять шагов приучают глаз быстрее тридцати'];
  const own = extract(__filename, '000320.37 T5:');
  const prevFile = path.join(__dirname, 'npc-000320.36.test.js');
  assert.ok(fs.existsSync(prevFile),
    'предыдущее звено цепи tests/npc-000320.36.test.js существует');
  const prev = extract(prevFile, '000320.36 T5:');
  const p36 = fs.readFileSync(prevFile, 'utf8');
  const discMine36 = [...p36.match(/const MINE = \[([\s\S]*?)\];/)[1]
    .matchAll(/'([^']*)'/g)].map((x) => x[1]);
  assert.deepEqual(EXPECT_ADDS, discMine36,
    'копии EXPECT_ADDS ≡ дисковой MINE-константе файла .36 '
    + '(правило 000390: формы ТОЛЬКО с диска — расхождение транскрипции '
    + 'ловится здесь); факт диска: ' + JSON.stringify(discMine36));
  assert.equal(own.length, 135,
    'guard-массив T5 этого файла — РОВНО 135 (пин по диску; вырез или '
    + 'лишний элемент ловятся здесь); факт: ' + own.length);
  assert.equal(new Set(own).size, own.length,
    'guard-массив этого файла — элементы уникальны (дубль ловится здесь)');
  assert.equal(prev.length, 131,
    'guard-массив T5 .36 — РОВНО 131 (то же число пинует T9 файла .36 — '
    + 'двойное покрытие); факт: ' + prev.length);
  assert.equal(new Set(prev).size, prev.length,
    'guard-массив .36 — элементы уникальны');
  const ownSet = new Set(own);
  const lost = [...new Set(prev)].filter((x) => !ownSet.has(x));
  assert.deepEqual(lost, [],
    'строгое включение prev ⊆ own — ни один элемент .36 не потерян; '
    + 'потеряно: ' + JSON.stringify(lost));
  const prevSet = new Set(prev);
  const adds = own.filter((x) => !prevSet.has(x));
  assert.deepEqual([...adds].sort(), [...EXPECT_ADDS].sort(),
    'дельта (own минус prev) — РОВНО 4 оборота Намёта = MINE-константа '
    + 'файла .36 (формула наследования '
    + 'memory/000320-accuracy_instructor.md); СВОИ 4 оборота канителя '
    + '(резерв .38 по memory/000320-crossbowman.md) в списке НЕ сидят; '
    + 'факт: ' + JSON.stringify(adds));
});
