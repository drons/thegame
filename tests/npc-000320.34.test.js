// --- T9: forbid-цепь — зуб длины/уникальности/включения (000372) -------------

test('T9: forbid-цепь 000372 (.33→.34) — guard-массив T5 этого файла РОВНО 123 и без дублей, предыдущего звена .33 РОВНО 119 и без дублей, prev ⊆ own, дельта — РОВНО 4 оборота Дымаря (формула наследования; хвост цепи — резерв 4 утварника НЕ в списке, он для .35)', () => {
  const extract = (file) => {
    const src = fs.readFileSync(file, 'utf8');
    const anchor = "test('" + "T5:";
    const at = src.indexOf(anchor);
    assert.ok(at >= 0,
      path.basename(file) + ': якорь T5 не найден — порча имени '
      + 'теста-носителя цепи ловится здесь (ERR_ASSERTION, не крах '
      + 'загрузки)');
    const m = src.slice(at).match(/for \(const w of \[([\s\S]*?)\]\)/);
    assert.ok(m,
      path.basename(file) + ': guard-массив не найден после якоря T5');
    return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
  };
  const EXPECT_ADDS = [
    'железо терпение любит больше силы', 'спешка портит край',
    'огонь проверяет, а не тешит', 'мастер не тот, кто не мажет, а тот, кто правит',
  ];
  const own = extract(__filename);
  const prevFile = path.join(__dirname, 'npc-000320.33.test.js');
  assert.ok(fs.existsSync(prevFile),
    'предыдущее звено цепи tests/npc-000320.33.test.js существует');
  const prev = extract(prevFile);
  const p33 = fs.readFileSync(prevFile, 'utf8');
  const discMine33 = [...p33.match(/const MINE = \[([\s\S]*?)\];/)[1]
    .matchAll(/'([^']*)'/g)].map((x) => x[1]);
  assert.deepEqual(EXPECT_ADDS, discMine33,
    'копии EXPECT_ADDS ≡ дисковой MINE-константе файла .33 '
    + '(правило 000390: формы ТОЛЬКО с диска — расхождение транскрипции '
    + 'ловится здесь); факт диска: ' + JSON.stringify(discMine33));
  assert.equal(own.length, 123,
    'guard-массив T5 этого файла — РОВНО 123 (пин по диску; вырез или '
    + 'лишний элемент ловятся здесь); факт: ' + own.length);
  assert.equal(new Set(own).size, own.length,
    'guard-массив этого файла — элементы уникальны (дубль ловится здесь)');
  assert.equal(prev.length, 119,
    'guard-массив T5 .33 — РОВНО 119 (то же число пинует T9 файла .33 — '
    + 'двойное покрытие); факт: ' + prev.length);
  assert.equal(new Set(prev).size, prev.length,
    'guard-массив .33 — элементы уникальны');
  const ownSet = new Set(own);
  const lost = [...new Set(prev)].filter((x) => !ownSet.has(x));
  assert.deepEqual(lost, [],
    'строгое включение prev ⊆ own — ни один элемент .33 не потерян; '
    + 'потеряно: ' + JSON.stringify(lost));
  const prevSet = new Set(prev);
  const adds = own.filter((x) => !prevSet.has(x));
  assert.deepEqual([...adds].sort(), [...EXPECT_ADDS].sort(),
    'дельта (own минус prev) — РОВНО 4 оборота Дымаря = MINE-константа '
    + 'файла .33 (формула наследования '
    + 'memory/000320-forge_instructor.md); СВОИ 4 оборота утварника '
    + '(резерв .35 по memory/000320-tool_smith.md) в списке НЕ сидят; '
    + 'факт: ' + JSON.stringify(adds));
});
