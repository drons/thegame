// Задача 000264 (здание w×h в городе рисуется w·h одноклеточными
// спрайтами; должно быть — один w×h-спрайт от якоря) — RED-тест
// wording (docs only; код игры и существующие тесты НЕ меняются на
// красной стадии).
//
// Контракт: memory/000264-city-3x3-sprite.md §4 (W1) — предложение
// «Рендер построек» в spec/buildings.md: старое per-cell wording
// «построенные игроком — ПО КЛЕТКАМ (w×h здание = w·h спрайтов)»
// УБИРАЕТСЯ; новое «построенные игроком — один w×h-спрайт от якоря
// (данные — per-cell записи w·h)» ЕСТЬ; гвард «базовые — 1×1»
// сохраняется (базовые здания остаются 1×1).
//
// Красное «отсутствием/присутствием» (осмысленно — правок SPEC ещё
// нет, не синтаксис: файл существует и читается, падение —
// ERR_ASSERTION по отсутствию/присутствию ТЕКСТА). Паттерн
// tests/spec-000259-wording.test.js: norm() (SPEC ломает строки,
// фразы-ассерты встают в строку после norm).
//
// expectedRedCount = 1 (W1). Вместе с 000264-U1, U2 (tests/
// dungeon-ui.test.js) и E1, E2 (tests/city-screen.test.js) — ровно
// 5 красных задачи.

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const BUILDINGS = norm(fs.readFileSync(
  path.join(ROOT, 'spec', 'buildings.md'), 'utf8'));

test('SPEC 000264 W1: buildings «Рендер построек» — «построенные игроком — один w×h-спрайт от якоря (данные — per-cell записи w·h)» ЕСТЬ; «построенные игроком — ПО КЛЕТКАМ (w×h здание = w·h спрайтов)» НЕТ; гвард «базовые — 1×1» ЕСТЬ', () => {
  assert.ok(
    BUILDINGS.includes(
      'построенные игроком — один w×h-спрайт от якоря ' +
      '(данные — per-cell записи w·h)'),
    'spec/buildings.md: новое wording «построенные игроком — один ' +
    'w×h-спрайт от якоря (данные — per-cell записи w·h)» отсутствует ' +
    '— сейчас «построенные игроком — ПО КЛЕТКАМ (w×h здание = w·h ' +
    'спрайтов)» (000264: один w×h-спрайт от якоря, данные — ' +
    'per-cell записи w·h)');
  assert.ok(
    !BUILDINGS.includes(
      'построенные игроком — ПО КЛЕТКАМ (w×h здание = w·h спрайтов)'),
    'старое wording «построенные игроком — ПО КЛЕТКАМ (w×h здание ' +
    '= w·h спрайтов)» осталось — переписать по 000264: один w×h-' +
    'спрайт от якоря');
  assert.ok(
    BUILDINGS.includes('базовые — 1×1'),
    'гвард-wording «базовые — 1×1» отсутствует (базовые здания ' +
    'остаются 1×1)');
});
