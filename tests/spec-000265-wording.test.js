// Задача 000265 (11 подтипов слотов 8..12 — собственные статичные
// спрайты, резолв по id каталога) — RED-тест wording (docs only; код
// игры и существующие тесты НЕ меняются на красной стадии).
//
// Контракт: memory/000265-subtype-building-sprites.md §4 — три правки
// spec/buildings.md:
//  1. «Расширение карты — подтипы слотов»: «спрайт — спрайт слота»
//     (фраза ЕДИНСТВЕННА в спеке) → «спрайт — свой, если есть в
//     каталоге (000265), иначе — спрайт слота»;
//  2. «Содержимое города»: + «подтипы с собственным спрайтом (000265)
//     — свой спрайт» (гвард «базовые — 1×1» сохраняется);
//  3. «Анимация (кадр-свитч)»: буллет — подтипы СТАТИЧНЫЕ, «НЕ
//     наследуют кадры таверны» (колодец/фонтан, слот 11).
//
// Красное «отсутствием/присутствием» (осмысленно — правок SPEC ещё
// нет, не синтаксис: файл существует и читается, падение —
// ERR_ASSERTION по отсутствию/присутствию ТЕКСТА). Паттерн
// tests/spec-000264-wording.test.js: norm() (SPEC ломает строки,
// фразы-ассерты встают в строку после norm).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const BUILDINGS = norm(fs.readFileSync(
  path.join(ROOT, 'spec', 'buildings.md'), 'utf8'));

test('SPEC 000265 S1: buildings — «спрайт — свой, если есть в каталоге (000265)» ЕСТЬ; «спрайт — спрайт слота» НЕТ; «подтипы с собственным спрайтом (000265) — свой спрайт» ЕСТЬ (город); «НЕ наследуют кадры таверны» ЕСТЬ (анимация)', () => {
  assert.ok(
    BUILDINGS.includes('спрайт — свой, если есть в каталоге (000265)'),
    'spec/buildings.md: новое wording «спрайт — свой, если есть в '
    + 'каталоге (000265), иначе — спрайт слота» отсутствует — '
    + 'сейчас «спрайт — спрайт слота» (000265: резолв по id '
    + 'каталога, свой статичный SVG подтипа)');
  assert.ok(
    !BUILDINGS.includes('спрайт — спрайт слота'),
    'старое wording «спрайт — спрайт слота» осталось — переписать по '
    + '000265: спрайт — свой, если есть в каталоге, иначе — слот');
  assert.ok(
    BUILDINGS.includes(
      'подтипы с собственным спрайтом (000265) — свой спрайт'),
    'spec/buildings.md «Содержимое города»: wording «подтипы с '
    + 'собственным спрайтом (000265) — свой спрайт» отсутствует — '
    + 'город отрисовывает подтип СВОИМ спрайтом, не слотовым');
  assert.ok(
    BUILDINGS.includes('НЕ наследуют кадры таверны'),
    'spec/buildings.md «Анимация (кадр-свитч)»: буллет о статичности '
    + 'подтипов («НЕ наследуют кадры таверны» — колодец/фонтан, '
    + 'слот 11) отсутствует — подтип со своим спрайтом статичен');
});
