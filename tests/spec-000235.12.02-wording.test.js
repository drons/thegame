const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — пины читают подфайлы
// напрямую. 000235.12.02: затронуты 2 файла — каждый readFileSync
// ОДИН РАЗ (паттерн 000244).
const GTIME = fs.readFileSync(path.join(ROOT, 'spec', 'game-time.md'), 'utf8');
const WMAP = fs.readFileSync(path.join(ROOT, 'spec', 'world-map.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл и секция существуют — осмысленная
// краснота, правок SPEC ещё нет).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

// Срезы: целый файл (H2 в обоих нет).
const GT = () => GTIME;
const WM = () => WMAP;

test('SPEC 000235.12.02 T1: game-time.md — смена дня по ЕДИНИЦАМ СТОИМОСТИ шагов: «стоимость шага 1 или 2 — см. spec/world-map.md «Плотность движения»» (оговорка + кросс-ссылка) и «день сменяется при накопленных steps_per_day единицах стоимости шагов»; исходная строка «успешных шагов» НЕ заменена', () => {
  const gt = GT();
  phrase(gt, 'spec/game-time.md',
    'стоимость шага 1 или 2 — см. spec/world-map.md «Плотность ' +
      'движения»',
    'оговорка «стоимость шага 1 или 2» (thick-шаг тикает общий ' +
      'счётчик на 2 — день может смениться на 20-м шаге по лесу) + ' +
      'кросс-ссылка на spec/world-map.md «Плотность движения» не ' +
      'зафиксирована');
  phrase(gt, 'spec/game-time.md',
    'день сменяется при накопленных steps_per_day единицах стоимости ' +
      'шагов',
    'день сменяется при накопленных ЕДИНИЦАХ СТОИМОСТИ шагов (1 или ' +
      '2), а не при физическом числе шагов, — не зафиксировано');
  phrase(gt, 'spec/game-time.md',
    'на глобальной карте, в подземельях и городах (общий счётчик ' +
      'шагов)',
    'guard: исходная строка «успешных шагов персонажа — на глобальной ' +
      'карте…» НЕ заменена (оговорка добавлена ПОСЛЕ неё, не вместо ' +
      'неё)');
});

test('SPEC 000235.12.02 T2: world-map.md «Плотность движения» — flame_step-лендинг: «1 шаг за ландинг (каст), НЕ за клетку» (000239 D1; длина луча не важна — один addStep(1) за каст); старая формулировка «flame_step-лендинг (000239 D1) — 1/клетку» удалена; клауза «Подземелье/город (клетки без террейна) — 1/клетку» сохранена', () => {
  const wm = WM();
  phrase(wm, 'spec/world-map.md', '1 шаг за ландинг (каст),',
    'flame_step-лендинг — 1 шаг за ЛАНДИНГ (каст) (один addStep(1) за ' +
      'каст — applyTeleportPlacement) не зафиксировано');
  phrase(wm, 'spec/world-map.md',
    'НЕ за клетку; счётчик — общий steps_per_day (spec/game-time.md)',
    '«НЕ за клетку» (длина луча не важна) + общий счётчик ' +
      'steps_per_day не зафиксировано');
  phrase(wm, 'spec/world-map.md',
    'Подземелье/город (клетки без террейна) — 1/клетку',
    'клауза «Подземелье/город (клетки без террейна) — 1/клетку» ' +
      'сохранена после перефразирования (от неё отделили только ' +
      'flame_step-часть)');
  const OLD_FLAME = 'flame_step-лендинг (000239 D1) — 1/' + 'клетку';
  assert.ok(!norm(wm).includes(OLD_FLAME),
    'старая формулировка «flame_step-лендинг (000239 D1) — 1/клетку» ' +
      'на месте (flame_step-лендинг приравнен к 1/клетку)');
});
