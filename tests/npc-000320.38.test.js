// --- T9: forbid-цепь — зуб длины/уникальности/включения (000372) -------------

test('000320.38 T9: forbid-цепь 000372 (.37→.38) — guard-массив T5 этого файла РОВНО 139 и без дублей, предыдущего звена .37 РОВНО 135 и без дублей, prev ⊆ own, дельта — РОВНО 4 оборота Канителя (формула наследования; хвост цепи — резерв 4 разведчика НЕ в списке, он для .39)', () => {
  const extract = (file, marker) => {
    const src = fs.readFileSync(file, 'utf8');
    const anchor = "test('" + marker;
    const at = src.indexOf(anchor);
    assert.ok(at >= 0,
      path.basename(file) + ': якорь T5 «' + marker + '» не найден — '
      + 'порча имени теста-носителя цепи ловится здесь (ERR_ASSERTION, '
      + 'не крах загрузки)');
    const m = src.slice(at).match(/for \(const w of \[([\s\S]*?)\]\)/);
    assert.ok(m,
      path.basename(file) + ': guard-массив не найден после якоря T5');
    return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
  };
  const EXPECT_ADDS = [
    'луки берут на просвет, а не на слух',
    'тетиву берегут до выстрела, а не после',
    'рогатка прощает дрожащие руки один раз',
    'верный замок важнее меткой руки'];
  const own = extract(__filename, '000320.38 T5:');
  const prevFile = path.join(__dirname, 'npc-000320.37.test.js');
  assert.ok(fs.existsSync(prevFile),
    'предыдущее звено цепи tests/npc-000320.37.test.js существует');
  const prev = extract(prevFile, '000320.37 T5:');
  const p37 = fs.readFileSync(prevFile, 'utf8');
  const discMine37 = [...p37.match(/const MINE = \[([\s\S]*?)\];/)[1]
    .matchAll(/'([^']*)'/g)].map((x) => x[1]);
  assert.deepEqual(EXPECT_ADDS, discMine37,
    'копии EXPECT_ADDS ≡ дисковой MINE-константе файла .37 '
    + '(правило 000390: формы ТОЛЬКО с диска — расхождение транскрипции '
    + 'ловится здесь); факт диска: ' + JSON.stringify(discMine37));
  assert.equal(own.length, 139,
    'guard-массив T5 этого файла — РОВНО 139 (пин по диску; вырез или '
    + 'лишний элемент ловятся здесь); факт: ' + own.length);
  assert.equal(new Set(own).size, own.length,
    'guard-массив этого файла — элементы уникальны (дубль ловится здесь)');
  assert.equal(prev.length, 135,
    'guard-массив T5 .37 — РОВНО 135 (то же число пинует T9 файла .37 — '
    + 'двойное покрытие); факт: ' + prev.length);
  assert.equal(new Set(prev).size, prev.length,
    'guard-массив .37 — элементы уникальны');
  const ownSet = new Set(own);
  const lost = [...new Set(prev)].filter((x) => !ownSet.has(x));
  assert.deepEqual(lost, [],
    'строгое включение prev ⊆ own — ни один элемент .37 не потерян; '
    + 'потеряно: ' + JSON.stringify(lost));
  const prevSet = new Set(prev);
  const adds = own.filter((x) => !prevSet.has(x));
  assert.deepEqual([...adds].sort(), [...EXPECT_ADDS].sort(),
    'дельта (own минус prev) — РОВНО 4 оборота Канителя = MINE-константа '
    + 'файла .37 (формула наследования '
    + 'memory/000320-crossbowman.md); СВОИ 4 оборота разведчика '
    + '(резерв .39 по memory/000320-scout.md) в списке НЕ сидят; '
    + 'факт: ' + JSON.stringify(adds));
});
