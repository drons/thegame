function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» (до следующего '\n## ' или конца).
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Срез H3-подраздела «### <name>» (до следующего '\n### ' или
// '\n## ' — что ближе).
function h3(sec, name) {
  const m = sec.match(new RegExp('^### ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j3 = sec.indexOf('\n### ', i + 1);
  const j2 = sec.indexOf('\n## ', i + 1);
  let j = -1;
  if (j3 !== -1 && (j2 === -1 || j3 < j2)) j = j3;
  else if (j2 !== -1) j = j2;
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Срез буллета поля «   * `<name>`» (до следующего буллета «   * `»).
function fieldBullet(text, name) {
  const m = text.match(new RegExp('^ {3}\\* `' + esc(name) + '`', 'm'));
  assert.ok(m, 'spec: поле «' + name + '» не найдено');
  const i = m.index;
  const j = text.slice(i + 1).search(/^ {3}\* `/m);
  return text.slice(i, j === -1 ? text.length : i + 1 + j);
}

// Срез буллета « * <prefix>» (1-пространство, без backtick-имени)
// до следующего «\n * ».
function bulletAt(text, prefix) {
  const i = text.indexOf(prefix);
  assert.notEqual(i, -1, 'spec: буллет «' + prefix + '» не найден');
  const j = text.indexOf('\n * ', i + 1);
  return text.slice(i, j === -1 ? text.length : j);
}

// Нормализация: коллапс белых (фразы, сломавшиеся переносом, встают
// в строку) + нижний регистр (needle — регистронезависимый).
function norm(s) {
  return s.replace(/\s+/g, ' ').toLowerCase();
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл существует — осмысленная краснота, правок
// SPEC ещё нет).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(norm(needle)),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

