// Задача 000436 (ретро-b33 «Дыра в зубах»): задача 000426 (мастер 408940e2)
// переписала 4 боевые spec-ячейки line-neutral правками, но её приёмочный гейт
// жил только в /tmp/docs426-grep.test.js (вне tests/) — ни один коммиченый тест
// содержимое ячеек НЕ пинует, регрессия прежней лжи зелёная. Этот файл заводит
// вечные зубы: (1) байт-строки четырёх честных ячеек spec/skills.md и spec/mobs.md,
// (2) grep-отсутствие четырёх старых лживых формулировок (скауп — ровно эти два
// spec-файла; бо́й-ячейки ПЕРВОИСТОЧНИКОМ живут в assets/skills/*.json — зона
// task/000426-01, здесь не дублируется), (3) уникальность честных маркёров
// (count===1 по файлу) и защищённые строки-соседи по образцу T7 000426-гейта.
//
// Якорь строки — ИМЯ строки « | <имя> | » (rowOf-контракт 000275: уникальность = 1,
// НЕ номер строки — дрейф-устойчивость). Число строк spec (skills.md 135 /
// mobs.md 146) здесь НЕ пинуется — владелец spec-split/000297 W3/000275 G2.
// mobs-соседи (паук/огонь/вода/фея/Орк-лучник) побайтово пинует
// tests/spec-000275-wording.test.js — здесь только rowOf-уникальность
// (двойное побайтовое владение дало бы ложный красный при чужом ре-пине).
//
// Тайтлы — маркёр «000436 T» (конвенция серии). Чтение — fs.readFileSync
// (без git show / формы «HEAD:» — head-guard-000395).

const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const SKILLS_TEXT = fs.readFileSync(path.join(ROOT, "spec", "skills.md"), "utf8");
const MOBS_TEXT = fs.readFileSync(path.join(ROOT, "spec", "mobs.md"), "utf8");
const SKILLS = SKILLS_TEXT.split("\n");
const MOBS = MOBS_TEXT.split("\n");

function rowOf(lines, name, file) {
  const rows = lines.filter((l) => l.startsWith(" | " + name + " | "));
  assert.equal(
    rows.length, 1,
    file + ": строка «" + name + "» — найдено " + rows.length
    + " (уникальность якоря « | <имя> | » нарушена)");
  return rows[0];
}

function countOf(text, needle) {
  return text.split(needle).length - 1;
}

// Четыре старые лжи (ровно эти байт-строки жили в spec до 408940e2 —
// извлечены из git show 408940e2^:spec/skills.md и :spec/mobs.md).
const LIE_MELEE = "урон в ближнем бою";
const LIE_MORALE = "действия на мораль врагов";
const LIE_TROLL_REGEN = "Регенерирует вне боя";
const LIE_SCORPION_FLEE = "отступает при ранении";

test("000436 T1: spec/skills.md — боевые ячейки «Сила»/«Харизма» честные (000426): байт-строка + присутствия", () => {
  assert.equal(
    rowOf(SKILLS, "Сила", "spec/skills.md"),
    " | Сила | Физическая мощь | Кол-во действий «Удар», урон без оружия | Переносимый вес, разрушение объектов |",
    "spec/skills.md «Сила»: боевая колонка переписана 000426 — безоружная база "
    + "3+⌊0.8·str⌋+⌊0.5·lv⌋ (combat.js playerAttack else-ветка), оружейный урон "
    + "от Силы НЕ зависит; прежняя ложь «урон в ближнем бою» запрещена");
  assert.ok(
    rowOf(SKILLS, "Сила", "spec/skills.md").includes("урон без оружия"),
    "spec/skills.md «Сила»: отсутствует «урон без оружия» — честная формулировка 000426");
  assert.ok(
    !rowOf(SKILLS, "Сила", "spec/skills.md").includes(LIE_MELEE),
    "spec/skills.md «Сила»: вернулась старая ложь «урон в ближнем бою» — "
    + "ближнебоевой урон от Силы не зависит (eq.damage·(1+dmgBonus), sheet.js)");
  assert.equal(
    rowOf(SKILLS, "Харизма", "spec/skills.md"),
    " | Харизма | Уверенность, самообладание и обаяние | ОТСРОЧЕНО: мораль врагов как подсистема отсутствует, прямого влияния Харизмы в бою нет («Быстрые предметы» — от Ловкости) | Диалоги, цены торговли, лояльность спутников |",
    "spec/skills.md «Харизма»: боевая колонка переписана 000426 — потребителей "
    + "Харизмы в src/combat.js РОВНО 0, морали врагов нет (побег = TIMID+hp<30%, "
    + "fear — fright); прежняя ложь про влияние на мораль запрещена");
  assert.ok(
    rowOf(SKILLS, "Харизма", "spec/skills.md").includes("мораль врагов как подсистема отсутствует"),
    "spec/skills.md «Харизма»: отсутствует «мораль врагов как подсистема отсутствует» — честная формулировка 000426");
  assert.ok(
    rowOf(SKILLS, "Харизма", "spec/skills.md").includes("прямого влияния Харизмы в бою нет"),
    "spec/skills.md «Харизма»: отсутствует «прямого влияния Харизмы в бою нет» — честная формулировка 000426");
  assert.ok(
    !rowOf(SKILLS, "Харизма", "spec/skills.md").includes(LIE_MORALE),
    "spec/skills.md «Харизма»: вернулась старая ложь «действия на мораль врагов» — "
    + "подсистемы морали врагов в бою нет (000426)");
});

