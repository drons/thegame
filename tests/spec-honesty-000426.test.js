test("000436 T3: отсутствие 4 старых лжей в обоих spec-файлах + уникальность честных маркёров + защищённые соседи (000426)", () => {
  for (const lie of [LIE_MELEE, LIE_MORALE, LIE_TROLL_REGEN, LIE_SCORPION_FLEE]) {
    assert.ok(
      !SKILLS_TEXT.includes(lie),
      "spec/skills.md: найдена старая ложь 000426-эпохи «" + lie + "» — "
      + "скауп зуба: spec/skills.md + spec/mobs.md");
    assert.ok(
      !MOBS_TEXT.includes(lie),
      "spec/mobs.md: найдена старая ложь 000426-эпохи «" + lie + "» — "
      + "скауп зуба: spec/skills.md + spec/mobs.md");
  }
  const honest = [
    [SKILLS_TEXT, "урон без оружия", "spec/skills.md"],
    [SKILLS_TEXT, "мораль врагов как подсистема отсутствует", "spec/skills.md"],
    [SKILLS_TEXT, "прямого влияния Харизмы в бою нет", "spec/skills.md"],
    [MOBS_TEXT, "ОТСРОЧЕНО: механики внебоевого регена мобов нет", "spec/mobs.md"],
    [MOBS_TEXT, "Ядовитый хвост", "spec/mobs.md"],
    [MOBS_TEXT, "отступления при ранении у нейтральных мобов нет", "spec/mobs.md"],
  ];
  for (const [text, marker, file] of honest) {
    assert.equal(
      countOf(text, marker), 1,
      file + ": честный маркёр 000426 «" + marker + "» встречается "
      + countOf(text, marker) + " раз (ожидалось 1 — дубль размывает пин ячейки)");
  }
  // Защищённые строки-соседи по образцу T7 000426-гейта: их 000426 не должна
  // была менять — побайтовые пины строк skills.md.
  assert.equal(
    rowOf(SKILLS, "Ловкость", "spec/skills.md"),
    " | Ловкость | Проворство, рефлексы и равновесие | Дистанция хода 1 + Ловкость/10 (целая часть) клеток за ход, «Быстрые предметы» | Скорость перемещения по карте |",
    "spec/skills.md «Ловкость»: защищённая соседняя строка 000426 изменена "
    + "(была побайтово цела в 408940e2)");
  assert.equal(
    rowOf(SKILLS, "Владение посохом", "spec/skills.md"),
    " | Владение посохом | +5% вероятность попадания посохом | Бой |",
    "spec/skills.md «Владение посохом»: защищённая соседняя строка 000426 "
    + "изменена (была побайтово цела в 408940e2)");
  assert.equal(
    rowOf(SKILLS, "Акробатика", "spec/skills.md"),
    " | Акробатика | +5% вероятность взойти в горы за уровень | Карта |",
    "spec/skills.md «Акробатика»: защищённая соседняя строка 000426 изменена "
    + "(ре-пин 000422 — горный лаз, сноска ОТСРОЧЕНО снята)");
  assert.equal(
    rowOf(SKILLS, "Застращивание", "spec/skills.md"),
    " | Застращивание | Шанс напугать моба уровнем ниже, заставив бежать | в бою; на карте — ОТСРОЧЕНО |",
    "spec/skills.md «Застращивание»: защищённая соседняя строка 000426 изменена "
    + "(000271: в бою реализовано; на карте — ОТСРОЧЕНО)");
  // mobs-соседи: побайтовый пин — у tests/spec-000275-wording.test.js
  // (W1–W4+G1); здесь — только уникальность rowOf-якорей (без дубля литералов).
  for (const name of ["Гигантский паук", "Огненный стихийник", "Водный стихийник", "Фея", "Орк-лучник"]) {
    rowOf(MOBS, name, "spec/mobs.md");
  }
});
