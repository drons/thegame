const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — единый текст = подфайлы (join('\n')).
// 000187 (ретро-20261011): область счётчика «(v1)» и 4 негативных фраз —
// ВСЕ spec/*.md (readdirSync + sort — как до разбивки, монолитный SPEC.md;
// supersede memory/000159-spec-split.md §3.4 «Осознанное сужение» —
// зафиксировано memory/000187-spec-structural-pins.md §2.3). readdirSync+
// sort, а не хардкод имён: область автоматически расширяется на будущие
// файлы spec/ (R1 пинит точный набор). Ложных срабатываний при расширении
// нет (проверено на 4156dcb): «(v1)» — ровно 1 (efir-spirit.md), 4
// негатива — 0 во всех файлах. Ассерты/хелперы — без правок.
const SPEC = fs.readdirSync(path.join(ROOT, 'spec'))
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => fs.readFileSync(path.join(ROOT, 'spec', f), 'utf8'))
  .join('\n');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H1-раздела: строка '# <name>' → до следующего '\n# '.
function h1(name) {
  const m = SPEC.match(new RegExp('^' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'SPEC.md: раздел «' + name + '» не найден');
  const i = m.index;
  const j = SPEC.indexOf('\n# ', i + 1);
  return SPEC.slice(i, j === -1 ? SPEC.length : j);
}

// Срез H2-подраздела «## <name>» внутри текста раздела.
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'SPEC.md: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const SPEC_N = norm(SPEC);
const BATTLE = () => norm(h2(h1('# Спутники'), 'Бой'));
const EFIR = () => norm(h2(h1('# Дух Эфира'), 'Бой'));

