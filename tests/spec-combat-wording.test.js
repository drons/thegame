const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SPEC = fs.readFileSync(path.join(ROOT, 'SPEC.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H1-раздела: строка '# <name>' → до следующего '\n# '.
function h1(name) {
  const m = SPEC.match(new RegExp('^' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'SPEC.md: раздел «' + name + '» не найден');
  const i = m.index;
  const j = SPEC.indexOf('\n# ', i + 1);
  return SPEC.slice(i, j === -1 ? SPEC.length : j);
}

// Срез H2-подраздела «## <name>» внутри текста раздела.
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'SPEC.md: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const SPEC_N = norm(SPEC);
const BATTLE = () => norm(h2(h1('# Спутники'), 'Бой'));
const EFIR = () => norm(h2(h1('# Дух Эфира'), 'Бой'));

test('SPEC 000181: «Спутники → Бой» — пулы наёмника квантитированы и ограничены наёмником (ТЗ п.5)', () => {
  const b = BATTLE();
  assert.ok(
    b.includes('движение — 1 клетка (наёмник; Эфир — 3 клетки и свои пулы, см. «Дух Эфира → Бой»);'),
    '«Спутники → Бой»: пулы не квантитированы или не ограничены наёмником — ' +
      'нужно «движение — 1 клетка (наёмник; Эфир — 3 клетки и свои пулы, ' +
      'см. „Дух Эфира → Бой“)» (код: makeAlly moveLeft = 1, 000168 D9; ' +
      'Эфир — c.efs.move = 3, combat.js:2456; без маркера общий буллет ' +
      'буквально противоречит Эфиру — межсекционный gap, review 000181)');
  assert.ok(
    b.includes('удар (дальность по роли) ИЛИ лечение — 1 действие за ход (наёмник);'),
    '«Спутники → Бой»: «удар (дальность по роли) ИЛИ лечение — 1 действие ' +
      'за ход» обязан быть ограничен наёмником (у Эфира — свои пулы ' +
      'c.efs.touch/spellInt/spellWis, combat.js:2451-2455, а не общий ' +
      'слот attackLeft: удар и лечение делят ОДИН слот, 000168 D9)');
  assert.ok(
    b.includes('блок/предметы/побег — только игрок.'),
    '«Спутники → Бой»: хвост буллета «блок/предметы/побег — только игрок» потерян');
  assert.ok(
    !SPEC_N.includes('движение, удар (дальность по роли)'),
    'старый неквантитированный список «движение, удар (дальность по роли), …» не удалён');
});

