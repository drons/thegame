function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» (до следующего '\n## ' или конца).
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Срез буллета поля «   * `<name>`» (до следующего буллета «   * `»).
function fieldBullet(text, name) {
  const m = text.match(new RegExp('^ {3}\\* `' + esc(name) + '`', 'm'));
  assert.ok(m, 'spec: поле «' + name + '» не найдено');
  const i = m.index;
  const j = text.slice(i + 1).search(/^ {3}\* `/m);
  return text.slice(i, j === -1 ? text.length : i + 1 + j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл существует — осмысленная краснота, правок
// SPEC ещё нет).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

// Конвенция 000159 R5: split('\n') + pop хвостового ''.
function specLines(s) {
  const lines = s.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  return lines.length;
}

test('SPEC 000296 R3: spec/npc.md — «Школы (обучение)»: формула 20 + 10 × L², интерпретация (L — текущий уровень ДО повышения), значения 0→20 / 1→30 / 2→60, граница 98030, кросс-ссылка на `обучение`', () => {
  const sc = h2(NPCMD, 'Школы (обучение)');
  phrase(sc, '«Школы (обучение)»', '20 + 10 × L²',
    'формула стоимости уровня (канон ×/², buildings.md:473) не зафиксирована');
  phrase(sc, '«Школы (обучение)»', 'L — ТЕКУЩИЙ уровень навыка ДО повышения',
    'интерпретация L = текущий уровень (не «целевой») не зафиксирована');
  phrase(sc, '«Школы (обучение)»', '0→20',
    'первый уровень 0→1 = 20 не зафиксирован');
  phrase(sc, '«Школы (обучение)»', '1→30', 'значение 1→30 не зафиксировано');
  phrase(sc, '«Школы (обучение)»', '2→60', 'значение 2→60 не зафиксировано');
  phrase(sc, '«Школы (обучение)»', '98030',
    'граница: шаг 99→100 = 98030 (максимум 100) не зафиксирована');
  phrase(sc, '«Школы (обучение)»', 'обучение',
    'кросс-ссылка на поле `обучение` («Архитектура хранения NPC») не зафиксирована');
  assert.equal(specLines(NPCMD), 48,
    'spec/npc.md: строк != 48 — раздел «Школы (обучение)» (000296: '
    + '7→16; 000297: +2 — перенос вложенных очков отменён; 000298: '
    + '+8 — лимит обучений + панель [I]; 000300: +11; 000334: +4 — '
    + 'строка «Очки обучения: N» — ТОЛЬКО Флогистон); 41→48: '
    + '000320.01 +7 — H2 «Несколько NPC на постройку» (хвост) + '
    + 'ре-пин SPEC_FILE_LINES (000159 §5.1) в том же коммите');
});

