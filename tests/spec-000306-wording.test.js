// Задача 000306 (SPEC-синхронизация: урон/лечение по степеням —
// множитель из каталога; протокол 000218/D11 — wording-пины В ТОМ
// ЖЕ коммите что правки spec; нормализация белых ОБЯЗАТЕЛЬНА —
// SPEC переносит строки ~64-70 кол.).
//
// Пины:
//   W1 — spec/spells.md H2 «Совершенствования (варианты заклинаний)»:
//       новый буллет «Урон по степеням — в каталоге: поле
//       множитель_степени…» (фрагменты: множитель к базе, строгий
//       рост в цепочке, фолбэк 1);
//   W2 — spec/efir-spirit.md «Бой»: урон-формула Эфира с
//       множителем_степени;
//   W3 — neg-пин: spec/efir-spirit.md НЕ содержит старую формулу
//       «(1 + 0.15 * (степень - 1))».
//
// Хелперы esc/h2/norm/phrase — 1:1 из
// tests/spec-000244-wording.test.js. expectedRedCount = 0 (файл
// входит в зелёную стадию: пины идут в том же коммите, что правки
// spec).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SPELLS = fs.readFileSync(path.join(ROOT, 'spec', 'spells.md'), 'utf8');
const EFIR = fs.readFileSync(
  path.join(ROOT, 'spec', 'efir-spirit.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» внутри текста (до следующего '\n## ').
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл и секция существуют — осмысленная краснота,
// правок SPEC ещё нет).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

const IMPROVE = () => h2(SPELLS, 'Совершенствования (варианты заклинаний)');

test('SPEC 000306 W1: spells.md «Совершенствования» — буллет «Урон по степеням»: поле множитель_степени — множитель к базе (4 + 0.5·атрибут), строгий рост в цепочке «база», фолбэк 1 (бит-в-бит степень 1)', () => {
  const s = IMPROVE();
  phrase(s, '«Совершенствования»', 'множитель_степени',
    'буллет «Урон по степеням» (000306) не зафиксирован');
  phrase(s, '«Совершенствования»', 'множитель к базе (4 + 0.5·атрибут)',
    'семантика поля — множитель к базе (4 + 0.5·атрибут), '
    + 'НЕ абсолютный урон (SPEC «Школы магии»: сила — от атрибута)');
  phrase(s, '«Совершенствования»',
    'значения строго растут со степенью (тест); без поля — 1 '
    + '(бит-в-бит степень 1)',
    'инвариант цепочки «база» + фолбэк 1 не зафиксированы');
});

test('SPEC 000306 W2: efir-spirit.md «Бой» — урон Эфира: round((4 + 0.5 * Инт) * множитель_степени * (1 + 0.05 * уровень лорда))', () => {
  phrase(EFIR, '«Дух Эфира»',
    'урон round((4 + 0.5 * Инт) * множитель_степени * '
    + '(1 + 0.05 * уровень лорда))',
    'урон-формула Эфира с каталожным множителем степени (000306) '
    + 'не задокументирована');
});

test('SPEC 000306 W3: efir-spirit.md — neg-пин: старой формулы «(1 + 0.15 * (степень - 1))» в файле НЕТ', () => {
  assert.ok(!EFIR.includes('(1 + 0.15 * (степень - 1))'),
    'efir-spirit.md: хардкод-константа 0.15 по степеням в формулах '
    + 'осталась — заменена на множитель_степени (каталог, 000306)');
});
