// ТЗ: три line-neutral правки В СТРОКЕ в spec/ —
// (1) spec/skills.md:42 «Кузнечная рука»: «+5% прочность собственного
//     снаряжения» → «+5% к качеству собственного крафта» (стат
//     equipmentDurabilityMult, src/sheet.js:529, имеет ЕДИНСТВЕННОГО
//     потребителя — качество крафта, src/craft.js:258-267 qualityMult;
//     durability-механики в игре нет);
// (2) spec/skills.md:52 «Акробатика»: пометка
//     «(ОТСРОЧЕНО: потребителей стата в коде нет)» (стат acroBonus,
//     src/sheet.js:514, — 0 потребителей; механик падения/лазания нет;
//     прецедент пометки — МИНИКАРТА spec/buildings.md:266);
// (3) spec/craft.md:82: слово «прочность» в связке с «Кузнечной рукой»
//     → «качество собственного крафта» (та же подмена, что (1)).
//
// Пины — LINE-INDEX (rows[41]/rows[51]/rows[81] по split('\n')) +
// sanity-гард имени навыка на закреплённой строке: сдвиг ЧИСЛА строк
// ловит R7 (spec-split.test.js: skills.md=100, craft.md=149), сдвиг
// СОДЕРЖИМОГО строки — sanity с понятным сообщением. Нормализация
// белых/регистра не нужна: пины — точные срединные подстроки строк
// markdown-таблицы/буллета одной строки (осознанное отличие от
// паттерна 000267, где norm по всему файлу для обёрнутого проза-текста).
//
// Красные «отсутствием» (осмысленно — правки SPEC ещё нет, не
// синтаксис: spec/skills.md и spec/craft.md существуют и читаются —
// падение ERR_ASSERTION по отсутствию нового текста / наличию старого
// на закреплённой строке; прецедент 000267).
//
// expectedRedCount (файл) = 3 (W1, W2, W3). Файл НЕ создаёт файлов в
// spec/ (R1 spec-split: ровно 23). Не содержит литерала «SPEC-453»
// (SPEC-453-GONE: скан tests/ + src/ строки 'SPEC ' + '453').

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — пины читают подфайлы напрямую.
// split('\n') БЕЗ pop хвостового '' — пины line-index по 1-базной
// нумерации (строка N = rows[N-1]); число строк держит R7.
const SKILLS = fs.readFileSync(path.join(ROOT, 'spec', 'skills.md'), 'utf8').split('\n');
const CRAFT = fs.readFileSync(path.join(ROOT, 'spec', 'craft.md'), 'utf8').split('\n');

test('SPEC 000273 W1: skills.md:42 «Кузнечная рука» — «+5% к качеству собственного крафта» (без «прочность»), line-neutral', () => {
  const row = SKILLS[41];
  assert.ok(
    row.includes('Кузнечная рука'),
    'skills.md:42: sanity — строка должна содержать «Кузнечная рука» '
    + '(сдвиг содержимого?; сдвиг числа строк — R7 spec-split)');
  assert.ok(
    row.includes('качеству собственного крафта'),
    'skills.md:42 «Кузнечная рука»: «+5% к качеству собственного '
    + 'крафта» отсутствует — единственный потребитель '
    + 'equipmentDurabilityMult (sheet.js:529) — качество КРАФТА '
    + '(craft.js:258-267 qualityMult/craftBonus); durability-механики '
    + 'нет (контракт P1, craft.md:28-29 «бонус к характеристикам '
    + 'предмета (качество)»)');
  assert.ok(
    !row.includes('прочност'),
    'skills.md:42 «Кузнечная рука»: слово «прочность» не согласуется '
    + 'с кодом — формула «качество собственного крафта» (контракт P1)');
});

test('SPEC 000273 W2: skills.md:52 «Акробатика» — пометка «(ОТСРОЧЕНО: потребителей стата в коде нет)», line-neutral', () => {
  const row = SKILLS[51];
  assert.ok(
    row.includes('Акробатика'),
    'skills.md:52: sanity — строка должна содержать «Акробатика» '
    + '(сдвиг содержимого?; сдвиг числа строк — R7 spec-split)');
  assert.ok(
    row.includes('ОТСРОЧЕНО'),
    'skills.md:52 «Акробатика»: пометка «(ОТСРОЧЕНО: потребителей '
    + 'стата в коде нет)» отсутствует — стат acroBonus (sheet.js:514) '
    + 'имеет 0 потребителей, механик падения/лазания нет; прецедент '
    + 'МИНИКАРТА buildings.md:266 (контракт P2)');
});

test('SPEC 000273 W3: craft.md:82 — «Кузнечная рука» — «качество собственного крафта» (без «прочность»), line-neutral', () => {
  const row = CRAFT[81];
  assert.ok(
    row.includes('Кузнечная рука'),
    'craft.md:82: sanity — строка должна содержать «Кузнечная рука» '
    + '(сдвиг содержимого?; сдвиг числа строк — R7 spec-split; в '
    + 'craft.md «Кузнечная рука» на 3 строках — только line-index)');
  assert.ok(
    !row.includes('прочност'),
    'craft.md:82: слово «прочность» в связке с «Кузнечной рукой» не '
    + 'согласуется с кодом (контракт P3: «качество собственного '
    + 'крафта»; ретро-F3 «craft.md уже согласован» опровергнут '
    + 'verify §3)');
  assert.ok(
    row.includes('качество собственного крафта'),
    'craft.md:82 «Кузнечная рука»: «качество собственного крафта» '
    + 'отсутствует (контракт P3: та же подмена, что skills.md:42)');
});
