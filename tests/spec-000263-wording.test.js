// Задача 000263 (скорость отрисовки мировой карты и городов/подземелий:
// чанковый рендер 16×16 с кэшем чанков) — RED-тест (docs only; код игры
// и существующие тесты НЕ меняются на красной стадии).
//
// CC-8 — SPEC-wording (красный «отсутствием» — осмысленно: правок SPEC
// ещё нет, все spec-файлы существуют и читаются, падение — ERR_ASSERTION
// по отсутствию ТЕКСТА). Паттерн tests/spec-000258-wording.test.js:
// norm() (SPEC ломает строки, фразы-ассерты встают в строку после
// нормализации белых + нижний регистр) + даш/×-толерантность.
//
// Контракт (memory/000263-chunked-render.md §8): spec/world-map.md,
// новый буллет «Чанковый рендер (000263)» рядом с «Рендер подземелья
// (000258)» (один markdown-буллет, как 000228/000258). Фразы-пины:
// «Чанковый рендер», «чанки 16×16», «offscreen» (или «офскрин»/
// «буфер чанка»), «кэш чанков» (+ «LRU»), «только видимые чанки»,
// «1 drawImage на чанк», «вода — по тайлу» (анимация не запекается),
// «инвалидация» + («зум»/«данные тайла»/«explored»), «динамические
// слои» поверх (мобы/игрок/эффекты), «результат идентичен предыдущему
// рендеру», «города не чанкуются (≤ 1024 клеток)».
//
// expectedRedCount += 1 (CC-8). RED = весь буллет отсутствует (все
// фразы missing).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

// Нормализация: белое → пробел + нижний регистр (фразы, сломавшиеся
// переносом строки, встают в строку; регистр «Чанковый»/«offscreen»/
// «LRU» сводится к одному виду).
function norm(s) {
  return s.replace(/\s+/g, ' ').toLowerCase();
}

const WORLD_MAP = norm(fs.readFileSync(
  path.join(ROOT, 'spec', 'world-map.md'), 'utf8'));

test('SPEC 000263 CC-8: world-map — буллет «Чанковый рендер (000263)» (все фразы-пины §8)', () => {
  const t = WORLD_MAP;
  const missing = [];
  // (1) заголовок буллета.
  if (!/чанковый рендер/.test(t)) missing.push('«Чанковый рендер»');
  // (2) размер чанка: 16×16 (×/x/✕-толерантность).
  if (!/чанк\w*\s+16\s*[×x✕]\s*16/.test(t)) missing.push('«чанки 16×16»');
  // (3) offscreen-буфер (3 эквивалента).
  if (!/(offscreen|офскрин|буфер чанка)/.test(t)) {
    missing.push('«offscreen» (или «офскрин»/«буфер чанка»)');
  }
  // (4) кэш чанков + LRU.
  if (!/кэш чанков/.test(t)) missing.push('«кэш чанков»');
  if (!/lru/.test(t)) missing.push('«LRU»');
  // (5) блит только видимых.
  if (!/только видимые чанки/.test(t)) missing.push('«только видимые чанки»');
  // (6) 1 drawImage на чанк («1»/«один»).
  if (!/(1|один)\s+drawimage\s+на\s+чанк/.test(t)) {
    missing.push('«1 drawImage на чанк»');
  }
  // (7) вода — по тайлу (анимация не запекается), даш-толерантность.
  if (!/вода\s*[—−-]\s*по тайлу/.test(t)) missing.push('«вода — по тайлу»');
  if (!/не запекается/.test(t)) {
    missing.push('анимация воды «не запекается»');
  }
  // (8) инвалидация + триггер (зум/данные тайла/explored).
  if (!/инвалидаци\w*/.test(t)) missing.push('«инвалидация»');
  if (!/зум|данные тайла|explored/.test(t)) {
    missing.push('триггеры инвалидации («зум»/«данные тайла»/«explored»)');
  }
  // (9) динамические слои поверх.
  if (!/динамические слои/.test(t)) missing.push('«динамические слои»');
  // (10) результат идентичен предыдущему рендеру.
  if (!/результат идентичен предыдущему рендеру/.test(t)) {
    missing.push('«результат идентичен предыдущему рендеру»');
  }
  // (11) города не чанкуются (≤ 1024 клеток).
  if (!/города не чанкуются/.test(t)) missing.push('«города не чанкуются»');
  if (!/1024\s+клеток/.test(t)) missing.push('(«≤ 1024 клеток»)');

  assert.deepEqual(missing, [],
    'spec/world-map.md: буллет «Чанковый рендер (000263)» — ' +
    (missing.length
      ? 'отсутствуют фразы-пины: ' + missing.join(', ')
      : 'буллет не найден целиком') +
    '; ожидается один markdown-буллет рядом с «Рендер подземелья ' +
    '(000258)», как у 000228/000258 (§8 контракта)');
});
