// КРАСНЫЕ (2 — падают потому, что правок spec ещё НЕТ; осмысленно:
// spec-файлы существуют и читаются — не синтаксис):
//   000255-W1  spec/items.md, срез H2 «Инвентарь»:
//                ПОЗИТИВ  — формула «(20 + 2 × уровень «Крепкая
//                           спина») слотов» (norm);
