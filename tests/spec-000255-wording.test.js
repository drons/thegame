// Нормализация белых ОБЯЗАТЕЛЬНА (SPEC переносит строки ~64-70
// кол.). 2× readFileSync ОТДЕЛЬНО (срез — в пределах ОДНОГО файла;
// паттерн 000235.06). Хелперы esc/h2/norm — 1:1 из
// tests/spec-combat-wording.test.js:41-66 (h1 НЕ нужен — срезы
// H2-уровня). В файле нет литерала «SPEC» + «453» (SPEC-453-GONE
// сканит tests/+src/) и «(v1)» — маркеры собираются из частей.
//
// expectedRedCount = 2 (W1, W2).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: spec-монолит разбит на spec/*.md — пины читают подфайлы
// напрямую. Оба затронутых файла — ОТДЕЛЬНО (срез в пределах файла;
// перетекания в соседний нет; паттерн 000235.06).
const ITEMS = fs.readFileSync(path.join(ROOT, 'spec', 'items.md'), 'utf8');
const SKILLS = fs.readFileSync(path.join(ROOT, 'spec', 'skills.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» внутри текста (до следующего '\n## ').
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const INVENTORY_SEC = () => norm(h2(ITEMS, 'Инвентарь'));
const SKILLS_N = norm(SKILLS);
// W1-негатив — needle ИЗ ЧАСТЕЙ (цельной старой строки в тест-файле
// нет — протокол 000187/000218: файл сканирует сам себя).
const W1_OLD = 'Инвентарь — INVENTORY_' + 'SLOTS (20) слотов';
const W2_OLD = '+10% к максимальному весу | Карта';

test('SPEC 000255 W1: items.md «Инвентарь» — формула «(20 + 2 × уровень «Крепкая спина») слотов»; база — INVENTORY_SLOTS; строка лимита веса без изменений', () => {
  const b = INVENTORY_SEC();
  assert.ok(
    b.includes('(20 + 2 × уровень «Крепкая спина») слотов'),
    '«Инвентарь»: формула слотов отсутствует — нужна «Инвентарь — '
    + '(20 + 2 × уровень «Крепкая спина») слотов; база — '
    + 'INVENTORY_SLOTS (20)» (000255: слоты растут +2 за уровень)');
  assert.ok(
    !INVENTORY_SEC().includes(W1_OLD),
    'spec/items.md «Инвентарь»: старая строка «' + W1_OLD + '» '
    + '(ровно 1 вхождение) не переписана на формулу 20 + 2 × уровень');
  assert.ok(
    b.includes('базовый переносимый вес (30 кг) × множитель «Крепкая спина»'),
    '«Инвентарь»: строка лимита веса УБРАНА/ПЕРЕПИСАНА — вес НЕ '
    + 'трогается (два независимых эффекта навыка: слоты — новое, '
    + 'вес — без изменений)');
});

test('SPEC 000255 W2: skills.md «Сила» — «Крепкая спина»: оба эффекта (+10% к максимальному весу, +2 слота инвентаря за уровень)', () => {
  assert.ok(
    SKILLS_N.includes('+10% к максимальному весу, +2 слота инвентаря за уровень'),
    'spec/skills.md: строка «Крепкая спина» без второго эффекта — '
    + 'нужно «+10% к максимальному весу, +2 слота инвентаря за '
    + 'уровень» (000255)');
  assert.ok(
    !SKILLS_N.includes(W2_OLD),
    'spec/skills.md: старая строка «' + W2_OLD + '» (ровно 1 '
    + 'вхождение) не расширена вторым эффектом навыка');
});
