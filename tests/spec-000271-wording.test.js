// expectedRedCount (W1) = 1.

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: spec-монолит разбит на spec/*.md — пины читают подфайлы
// напрямую.
const SKILLS = fs.readFileSync(path.join(ROOT, 'spec', 'skills.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» внутри текста (до следующего '\n## ').
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

const SKILLS_N = norm(h2(SKILLS, 'Вторичные навыки'));

test('SPEC 000271 W1: skills.md «Застращивание» — «Тип эффекта» «в бою; на карте — ОТСРОЧЕНО» (карта — отсрочено осознанно)', () => {
  assert.ok(
    SKILLS_N.includes('Шанс напугать моба уровнем ниже, заставив бежать | в бою; на карте — ОТСРОЧЕНО'),
    'spec/skills.md строка «Застращивание»: нужен «Шанс напугать моба уровнем ниже, заставив бежать | в бою; на карте — ОТСРОЧЕНО» (000271: эффект реализован в бою; на карте — отдельная ДИЗАЙН-задача)');
  const rows = SKILLS.split('\n');
  assert.ok(
    !rows.some((l) => l.includes('Застращивание') && l.includes('Карта/Бой')),
    'spec/skills.md: строка «Застращивание» ещё содержит «Карта/Бой» — ячейка «Тип эффекта» не переписана (негатив по сочетанию: голый «Карта/Бой» в строках других навыков — легитимен)');
  assert.ok(
    rows.some((l) => l.includes('Предводитель') && l.includes('Бой/Карта')),
    'КОНТРОЛЬ: строка Харизмы «Предводитель» с «Бой/Карта»-ячейкой на месте (не смешалась)');
  assert.ok(
    rows.some((l) => l.includes('Артист') && l.includes('Бой/Карта')),
    'КОНТРОЛЬ: строка Харизмы «Артист» с «Бой/Карта»-ячейкой на месте (не смешалась)');
});
