// На RED-стадии файла нет (D3 контракта) — коммитится на GREEN.
//   W1  spec/skills.md, срез H2 «Вторичные навыки» (строка таблицы
//       уникальна по файлу; срез уже ограничивает «Харизму»):
//         ПОЗИТИВ  — «Шанс напугать моба уровнем ниже, заставив
