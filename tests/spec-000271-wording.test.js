// Нормализация белых ОБЯЗАТЕЛЬНА (SPEC переносит строки ~64-70
// кол.). Хелперы esc/h2/norm — 1:1 из
// tests/spec-000255-wording.test.js. В файле нет литерала «SPEC» +
// «453» (SPEC-453-GONE сканит tests/+src/). Файл НЕ создаёт файлов
// в spec/ (R1 spec-split: ровно 23).
