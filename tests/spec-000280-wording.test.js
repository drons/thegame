const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// 000159: SPEC.md разбит на spec/*.md — пины читают подфайлы напрямую.
// split('\n') БЕЗ pop хвостового '' — число строк держит R7.
const SKILLS = fs.readFileSync(path.join(ROOT, 'spec', 'skills.md'), 'utf8').split('\n');

test('SPEC 000286 W1: GLOBAL-негатив — ни одна строка spec/skills.md не содержит «Карта/Бой» (инвариант memory/000280 §3)', () => {
  assert.ok(
    !SKILLS.some((l) => l.includes('Карта/Бой')),
    'spec/skills.md: найдена строка с «Карта/Бой» — откат нормализации 000280 '
    + '(канон: ячейки «Тип эффекта» читаются «Бой/Карта»; «Бой/Карта» не '
    + 'содержит подстроки «Карта/Бой» — 8 легитимных ячеек guard не ломают)');
});

test('SPEC 000286 W2: skills.md:53 «Тать» — effect-ячейка «Колодец: +5% шанс предмета на дне» (фантом «замки/ловушки/кража» → реализованный колодец 45), line-neutral', () => {
  const row = SKILLS.find((l) => l.includes('Тать'));
  assert.ok(row !== undefined,
    'spec/skills.md: строка «Тать» не найдена (сдвиг строки? — R7 spec-split)');
  assert.ok(
    row.includes('Колодец: +5% шанс предмета на дне'),
    'skills.md:53 «Тать»: «Колодец: +5% шанс предмета на дне» отсутствует — '
    + 'единственный консьюмер thiefBonus — колодец 45 '
    + '(building-effects.js:1741/1899, spec/buildings.md:258); «Открывание '
    + 'замков, снятие ловушек, кража» — фантом с 0 консьюмеров (контракт D1; '
    + 'JSON desc 000017 заперт V3-пином, UI-тултип рендерит именно её)');
  assert.ok(
    !row.includes('Открывание замков') && !row.includes('снятие ловушек')
    && !row.includes('кража'),
    'skills.md:53 «Тать»: фантом-текст «Открывание замков, снятие ловушек, '
    + 'кража» ещё на месте (0 консьюмеров — механик в коде нет)');
  assert.ok(
    row.includes('Бой/Карта'),
    'skills.md:53 «Тать»: ячейка «Тип эффекта» «Бой/Карта» изменена — ТЗ '
    + 'меняет только desc-ячейку (осознанный разнобой vs JSON «Карта» — '
    + 'memory/000280 §4)');
});

test('SPEC 000286 W3: skills.md:88 «Артист» — обе части живы, без маркера «ОТСРОЧЕНО» (контракт D2: finding ретро опровергнут)', () => {
  const row = SKILLS.find((l) => l.includes('Артист'));
  assert.ok(row !== undefined,
    'spec/skills.md: строка «Артист» не найдена (сдвиг строки? — R7 spec-split)');
  assert.ok(
    row.includes('Заработок на выступлениях') && row.includes('снижение агрессии'),
    'skills.md:88 «Артист»: пропала часть эффекта — «Заработок на '
    + 'выступлениях» (performanceIncomeMult, таверна 44_perform) и '
    + '«снижение агрессии» (refusalChance, companions.js:189-198 — сырой '
    + 'уровень Артиста; 0.05/ур — global-settings.js:152)');
  assert.ok(
    !row.includes('ОТСРОЧЕНО'),
    'skills.md:88 «Артист»: маркер «ОТСРОЧЕНО» на ЖИВОЙ механике — finding '
    + '«0 консьюмеров» опровергнут (контракт D2; механика заперта '
    + 'tests/companions.test.js:318-345 + tests/global-settings.test.js:317)');
  assert.ok(
    row.includes('Бой/Карта'),
    'skills.md:88 «Артист»: ячейка «Тип эффекта» «Бой/Карта» изменена — '
    + 'ТЗ не меняет её (CONTROL W1-000271 :87/:88)');
});
