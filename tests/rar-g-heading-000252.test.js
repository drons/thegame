const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const UI = fs.readFileSync(path.join(__dirname, 'ui.test.js'), 'utf8');

test('000252 H1: заголовок пина 230.07-RAR-G = телу: «каталог 484 шт. … прочие 197» (ре-пины 000235.08/000235.09/000230.11 дописаны; финализация merge 2026-10-24: 307 → 457, 154 → 172 (волны 000230.12–.15 + 000235.10); ре-пин 000230.19: 457 → 459 (+2 torso-набора в skip-ветку); ре-пин 000235.11: 459 → 484, 172 → 197 (+25 свитков 000460–000484, rarity нет); 207/104 устарели)', () => {
  const heading = UI.split('\n').filter(l => l.startsWith("test('230.07-RAR-G "));
  assert.equal(heading.length, 1,
    "строка test('230.07-RAR-G … — ровно одна (L49 — комментарий, не матчит); найдено: "
    + heading.length);
  const line = heading[0];
  assert.ok(line.includes('каталог 484 шт.'),
    'заголовок — «каталог 484 шт.» (тело: data.ITEMS.length = 484, L755); факт: ' + line);
  assert.ok(line.includes('прочие 197'),
    'заголовок — «прочие 197» (тело: others = 197, L770); факт: ' + line);
  assert.ok(!line.includes('207 шт.'),
    'устаревшее «207 шт.» (срез 000230.10) — отсутствует; факт: ' + line);
  assert.ok(!line.includes('прочие 104'),
    'устаревшее «прочие 104» (срез 000230.10) — отсутствует; факт: ' + line);
});
