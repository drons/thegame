const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const NPCMD = fs.readFileSync(path.join(ROOT, 'spec', 'npc.md'), 'utf8');

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Срез H2-подраздела «## <name>» (до следующего '\n## ' или конца).
function h2(sec, name) {
  const m = sec.match(new RegExp('^## ' + esc(name) + '\\s*$', 'm'));
  assert.ok(m, 'spec: подраздел «' + name + '» не найден');
  const i = m.index;
  const j = sec.indexOf('\n## ', i + 1);
  return sec.slice(i, j === -1 ? sec.length : j);
}

// Нормализация белых: фразы, сломавшиеся переносом, встают в строку.
function norm(s) {
  return s.replace(/\s+/g, ' ');
}

// positive-needle в срезе (нормализованном): падение — ERR_ASSERTION
// «фраза не найдена» (файл существует — осмысленная краснота, правок
// SPEC ещё нет).
function phrase(slice, label, needle, why) {
  assert.ok(
    norm(slice).includes(needle),
    label + ': фраза не найдена: «' + needle + '» — ' + why);
}

// Конвенция 000159 R5: split('\n') + pop хвостового ''.
function specLines(s) {
  const lines = s.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  return lines.length;
}

test('SPEC 000298 S1: spec/npc.md — «Школы (обучение)»: блок «Лимит обучений (задача 000298)» — 10 за уровень, −1 за обучение, плоский сброс в 10, reason; 26 строк', () => {
  const sc = h2(NPCMD, 'Школы (обучение)');
  phrase(sc, '«Школы (обучение)»', 'Лимит обучений (задача 000298):',
    'заголовок блока не зафиксирован');
  phrase(sc, '«Школы (обучение)»', 'не более 10 обучений за уровень персонажа',
    'лимит 10 за уровень (D1) не зафиксирован');
  phrase(sc, '«Школы (обучение)»', '10 учебных действий на текущий уровень Флогистона',
    'интерпретация «за уровень» (D1) не зафиксирована');
  phrase(sc, '«Школы (обучение)»', 'суммарно по всем навыкам и всем NPC',
    'бюджет общий по всем навыкам и NPC (D1) не зафиксирован');
  phrase(sc, '«Школы (обучение)»', 'каждое успешное обучение в школе — −1',
    'затрата −1 за успешное обучение (D3), «−» U+2212, не зафиксирована');
  phrase(sc, '«Школы (обучение)»', 'плоский сброс в 10',
    'сброс бюджета в 10 при ап-левеле (D5) не зафиксирован');
  phrase(sc, '«Школы (обучение)»', 'остаток не переносится',
    'flat reset: остаток не переносится (D5) не зафиксировано');
  phrase(sc, '«Школы (обучение)»', 'Крафт-наставничество (раздел «Крафт») лимитом не покрывается',
    'исключение крафт-наставничества (D1) не зафиксировано');
  phrase(sc, '«Школы (обучение)»', 'нет очков обучения на этом уровне',
    'reason отказа (D4) не зафиксирован');
  assert.equal(specLines(NPCMD), 48,
    'spec/npc.md: строк != 48 (18 → 26: +8 строк блока «Лимит '
    + 'обучений (задача 000298)» в конец раздела; 26 → 37: 000300 '
    + '+11 — блок «Обучение в школах (задача 000300…)» в конец '
    + 'раздела; 37 → 41: 000334 +4 — строка «Очки обучения: N» — '
    + 'ТОЛЬКО Флогистон; 41 → 48: 000320.01 +7 — H2 «Несколько NPC '
    + 'на постройку») + ре-пин '
    + 'SPEC_FILE_LINES (000159 §5.1) и guard wording 000296/000297 '
    + '18 → 26 в том же коммите');
});

