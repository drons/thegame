function buildDescription(m) {
  const lines = [];
  lines.push(`Общее впечатление. ${m.desc.impression}`);
  lines.push(`Силуэт и сложение. ${m.desc.silhouette}`);
  lines.push(`Голова и лицо. ${m.desc.head}`);
  lines.push(`Снаряжение, броня, оружие. ${m.desc.gear}`);
  lines.push('Цветовая схема (HEX):');
  for (const [hex, label] of Object.values(m.palette)) {
    lines.push(`- ${hex} — ${label}`);
  }
  lines.push(`Детали. ${m.desc.details}`);
  lines.push(`Арт-дирекшн. ${m.desc.direction}`);
  return lines.join('\n');
}

